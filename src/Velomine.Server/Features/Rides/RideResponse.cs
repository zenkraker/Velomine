namespace Velomine.Server.Features.Rides;

/// <summary>Time in one training zone. <c>To</c> is null for the open-ended top zone. Boundaries are bpm or watts.</summary>
public sealed record ZoneTime(int Zone, int From, int? To, double Seconds);

/// <summary>A ride as the API shows it. Times are UTC; distances in metres, times in seconds, speeds in metres per second.</summary>
public sealed record RideResponse(
    Guid Id,
    string Status,
    string? Error,
    Guid? DuplicateOf,
    string FileName,
    DateTimeOffset UploadedAt,
    DateTimeOffset? StartTime,
    int? UtcOffsetMinutes,
    string? Device,
    double? DistanceM,
    double? ElapsedS,
    double? MovingS,
    double? ElevationGainM,
    double? ElevationLossM,
    double? AvgSpeedMs,
    double? MaxSpeedMs,
    string? SpeedSource,
    int? AvgPowerW,
    int? MaxPowerW,
    int? NormalizedPowerW,
    double? IntensityFactor,
    double? Tss,
    double? Trimp,
    int? AvgHeartRate,
    int? MaxHeartRate,
    int? AvgCadence,
    Guid? BikeId,
    ZoneTime[]? HeartRateZones = null,
    ZoneTime[]? PowerZones = null)
{
    public static RideResponse From(Ride r) => new(
        r.Id,
        r.Status.ToString().ToLowerInvariant(),
        r.Error,
        r.DuplicateOf,
        r.FileName,
        r.UploadedAt,
        r.StartTime,
        r.UtcOffsetMinutes,
        r.Device,
        r.DistanceM,
        r.ElapsedS,
        r.MovingS,
        r.ElevationGainM,
        r.ElevationLossM,
        r.AvgSpeedMs,
        r.MaxSpeedMs,
        r.SpeedSource?.ToString().ToLowerInvariant(),
        r.AvgPowerW,
        r.MaxPowerW,
        r.NormalizedPowerW,
        r.IntensityFactor,
        r.Tss,
        r.Trimp,
        r.AvgHeartRate,
        r.MaxHeartRate,
        r.AvgCadence,
        r.BikeId);
}
