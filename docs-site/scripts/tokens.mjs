// Writes src/styles/tokens.css from docs/design/tokens.json, the one source the app also follows, so the docs cannot drift.
import { readFileSync, writeFileSync } from 'node:fs';

const t = JSON.parse(readFileSync(new URL('../../docs/design/tokens.json', import.meta.url), 'utf8'));
const block = (selector, lines) => `${selector} {\n${lines.map((l) => `  ${l}`).join('\n')}\n}\n`;

const shared = [
  ...t.spacing.tokens.map((x) => `--vm-${x.name}: ${x.value};`),
  ...t.radius.tokens.map((x) => `--vm-${x.name}: ${x.value};`),
  `--vm-font-sans: ${t.type.families.sans};`,
  `--vm-font-display: ${t.type.families.display};`,
  `--vm-blur-glass: ${t.blur.tokens[0].value};`,
  ...t.type.groups.flatMap((g) => g.styles.flatMap((s) => [
    `--vm-${s.name}-size: ${s.fontSize};`,
    `--vm-${s.name}-line: ${s.lineHeight};`,
    `--vm-${s.name}-weight: ${s.fontWeight};`,
  ])),
];
const theme = (id) => [
  ...t.color.tokens.map((x) => `--vm-${x.name}: ${x.value[id]};`),
  ...t.shadow.tokens.map((x) => `--vm-${x.name}: ${x.value[id]};`),
];

writeFileSync(
  new URL('../src/styles/tokens.css', import.meta.url),
  `/* Generated by scripts/tokens.mjs from docs/design/tokens.json. Do not edit. */\n` +
    block(':root', [...shared, ...theme('night')]) + // Starlight's default theme is dark: night.
    block(":root[data-theme='light']", theme('day')),
);
